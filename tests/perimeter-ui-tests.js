class Element {
  constructor(id) {
    this.id = id;
    this.value = ({ "length-input": "4", "shape-type": "square", "quantity-input": "1",
      "color-input": "#087f75", "width-input": "5", "dash-input": "solid" })[id] || "";
    this.options = id === "dash-input" ? [{ value: "solid" }, { value: "dashed" }] :
      id === "split-kind" ? [{ value: "equal" }, { value: "custom" }] : [];
    this.dataset = {};
    this.style = {};
    this.listeners = {};
    this.attributes = {};
    this.classList = { toggle: () => {} };
    this.parentElement = { style: {}, classList: { toggle: () => {} } };
    this.innerHTML = "";
    this.open = false;
    this.hidden = ["style-panel", "more-menu", "library-panel", "selection-box"].includes(id);
  }
  addEventListener(name, callback) { this.listeners[name] = callback; }
  fire(name, event = {}) { this.listeners[name]?.({ preventDefault() {}, button: 0, target: this, ...event }); }
  setAttribute(name, value) { this.attributes[name] = value; }
  createSVGPoint() { return { x: 0, y: 0, matrixTransform() {
    const { x, y } = this;
    // Native DOMPoint coordinates are prototype properties, not spreadable own fields.
    return Object.create({ get x() { return x; }, get y() { return y; } });
  } }; }
  getScreenCTM() { return { a: this.screenScale || 1, inverse: () => ({}) }; }
  getBoundingClientRect() { return { width: 1000, height: 520 }; }
  setPointerCapture() {}
  showModal() { this.open = true; }
  close() { this.open = false; }
  querySelector(selector) {
    const name = selector.match(/name="([^"]+)"/)?.[1];
    const value = this.innerHTML.match(new RegExp('name="' + name + '"[^>]*value="([^"]+)"'))?.[1];
    return { value };
  }
}

